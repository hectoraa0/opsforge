# OpsForge v0.7 — restore verification in a NEW, disposable database within PostgreSQL Pod.
# NEVER restores over the live 'opsforge' database.
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$BackupPath,
    [switch]$KeepRestoredDatabase
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$context = 'kind-opsforge'
$namespace = 'opsforge'
$pod = 'opsforge-db-0'
$user = 'opsforge'

function Assert-NativeSuccess([string]$Step) {
    if ($LASTEXITCODE -ne 0) { throw "$Step failed (exit code $LASTEXITCODE)" }
}

$resolved = Resolve-Path -LiteralPath $BackupPath -ErrorAction Stop
$local = $resolved.ProviderPath
$sumPath = $local + '.sha256'
if (-not (Test-Path -LiteralPath $sumPath)) { throw "Missing checksum companion file: $sumPath" }
$expected = ((Get-Content -LiteralPath $sumPath -TotalCount 1) -split '\s+')[0].ToLowerInvariant()
if ($expected -notmatch '^[a-f0-9]{64}$') { throw 'Malformed SHA-256 checksum file.' }
$actual = (Get-FileHash -LiteralPath $local -Algorithm SHA256).Hash.ToLowerInvariant()
if ($actual -ne $expected) { throw 'SHA-256 mismatch. The backup file may be damaged. Refusing to restore.' }

$phase = & kubectl --context $context -n $namespace get pod $pod -o 'jsonpath={.status.phase}'
Assert-NativeSuccess 'Check PostgreSQL pod'
if ((($phase | Out-String).Trim()) -ne 'Running') { throw 'PostgreSQL pod is not Running.' }

# The restoration target is generated by this script; it cannot equal the production DB.
$restoreDb = 'opsforge_restore_' + (Get-Date).ToUniversalTime().ToString('yyyyMMddHHmmss') + '_' + [guid]::NewGuid().ToString('N').Substring(0, 6)
$remote = '/tmp/opsforge-restore-' + [guid]::NewGuid().ToString('N') + '.dump'
$created = $false
$remoteUploaded = $false

try {
    Write-Host "[1/4] Uploading checksum-verified archive into $pod..."
    $target = "${namespace}/${pod}:$remote"
    # Avoid passing an absolute Windows path (C:\...) to kubectl cp: the colon
    # is otherwise interpreted as a remote host/pod delimiter.
    Push-Location -LiteralPath (Split-Path -Parent $local)
    try {
        & kubectl --context $context cp ("./" + [IO.Path]::GetFileName($local)) $target
        Assert-NativeSuccess 'kubectl cp'
    } finally {
        Pop-Location
    }
    $remoteUploaded = $true

    & kubectl --context $context -n $namespace exec $pod -- pg_restore --list $remote | Out-Null
    Assert-NativeSuccess 'Verify PostgreSQL archive'

    Write-Host "[2/4] Creating isolated test database $restoreDb..."
    & kubectl --context $context -n $namespace exec $pod -- createdb -U $user $restoreDb
    Assert-NativeSuccess 'createdb'
    $created = $true

    Write-Host '[3/4] Restoring the dump into the test database (NOT production)...'
    & kubectl --context $context -n $namespace exec $pod -- pg_restore -U $user --no-owner --no-acl --exit-on-error -d $restoreDb $remote
    Assert-NativeSuccess 'pg_restore'

    Write-Host '[4/4] Verifying restored incidents table and counting records...'
    $countResult = & kubectl --context $context -n $namespace exec $pod -- psql -U $user -d $restoreDb -X -A -t -v ON_ERROR_STOP=1 -c 'SELECT count(*) FROM public.incidents;'
    Assert-NativeSuccess 'Verify incidents table'
    $countText = ($countResult | Out-String).Trim()
    $count = 0L
    if (-not [long]::TryParse($countText, [ref]$count)) { throw "Unexpected database count result: $countText" }
    Write-Host 'RESTORE VERIFIED' -ForegroundColor Green
    Write-Host "Restored database: $restoreDb"
    Write-Host "Incident rows in restored backup: $count"
    Write-Host 'The original opsforge database and its Kubernetes PVC have not been replaced.'
} finally {
    if ($created -and -not $KeepRestoredDatabase) {
        Write-Host 'Removing the temporary test database...'
        & kubectl --context $context -n $namespace exec $pod -- dropdb -U $user $restoreDb
        if ($LASTEXITCODE -ne 0) { Write-Warning "Could not remove test database $restoreDb. Check it manually." }
    } elseif ($created) {
        Write-Host "Preserved test database: $restoreDb (remove manually after inspection)."
    }
    if ($remoteUploaded) {
        & kubectl --context $context -n $namespace exec $pod -- rm -f $remote 2>$null | Out-Null
        if ($LASTEXITCODE -ne 0) { Write-Warning 'Unable to remove temporary remote archive.' }
    }
}
